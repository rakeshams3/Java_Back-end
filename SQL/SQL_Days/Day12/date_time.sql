MySQL Date & Time Functions
1. Current Date & Time
NOW()
LOCALTIME()
SYSDATE()
2. Current Date
CURDATE()
CURRENT_DATE()
3. Current Time
CURTIME()
CURRENT_TIME()

4. Extract Date/Time
DATE()
TIME()
YEAR()
MONTH()
DAY()
MONTHNAME()
DAYNAME()


5. Date Difference
DATEDIFF()
TIMESTAMPDIFF()

Units for TIMESTAMPDIFF():

YEAR
MONTH
DAY
HOUR
MINUTE
SECOND


6. Add/Subtract Date
DATE_ADD()
DATE_SUB()

Must Remember Syntax
SELECT NOW();

SELECT CURDATE();

SELECT CURTIME();

SELECT DATE('2026-06-27 10:30:02');

SELECT TIME('2026-06-27 10:30:02');

SELECT DAYNAME('2026-06-27');

SELECT MONTHNAME('2026-06-27');

SELECT DATEDIFF('2026-06-27','2026-06-20');

SELECT TIMESTAMPDIFF(YEAR,'2000-01-01','2026-06-27');

SELECT DATE_ADD('2026-06-27', INTERVAL 5 DAY);

SELECT DATE_SUB('2026-06-27', INTERVAL 5 DAY);
