📝 SQL Basic Notes (1-Page Cheat Sheet)
1. SELECT
SELECT * FROM student;
SELECT name, marks FROM student;


2. WHERE
SELECT * FROM student
WHERE marks > 80;

3. Comparison Operators
Operator	Meaning
=	Equal
!= or <>	Not Equal
>	Greater Than
<	Less Than
>=	Greater Than or Equal
<=	Less Than or Equal

Example:

WHERE age >= 21;


4. BETWEEN
WHERE marks BETWEEN 80 AND 90;

✅ Includes both 80 and 90.
