Notes

Data:
Data can be facts, statistics, audio, video or images.

TYPES OF DATA

Structured data:
Collection of organized data is called as Structured data.

Semi Structured data:
Collection of partially organized data is called as Semi Structured data.

Unstructured Data:
Collection of Unorganized data is called as Unstructured data.

Database
Database is a collection of organized data

Relational Database
Relational Database is a database where data is organized in tabular structure

Non-Relational Database
Non Relational Databases do not use tabular structure to store the data, In Non Relational Databases data is stored in key:value pairs or graphs or in documents

RDBMS
Relational database Management systems/ softwares is used to manage Relational Databases

NO SQL
Non Relational Databases Management softwares are used to manage Non Relational Databases.


SQL

Structured Query Language

SQL is a structured query language which is used to communicate with the Relational Database Management Softwares to manage Relational Databases.
